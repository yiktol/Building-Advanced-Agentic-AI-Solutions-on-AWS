#!/bin/bash
# Generate the repo-root .env from deployed CloudFormation stack outputs.
#
# Queries the same stacks Home.py / agentcore_utils.py read, then writes a
# fresh .env with only the keys that actually resolved. No resource ids are
# hardcoded (except the two fixed DynamoDB table names, which are fixed by the
# module 3 template). Idempotent: re-running regenerates the file cleanly.
#
# Usage: bash deploy/generate-env.sh
#   AWS_REGION   region to query (default ap-southeast-1)
#
# Does NOT deploy anything; read-only describe-stacks calls only.

set -euo pipefail

REGION="${AWS_REGION:-ap-southeast-1}"
ENV_FILE="$(cd "$(dirname "$0")/.." && pwd)/.env"
TMP_FILE="$(mktemp "${ENV_FILE}.XXXXXX")"

trap 'rm -f "$TMP_FILE"' EXIT

# cfn_output STACK OUTPUT_KEY -> prints the output value, or empty if the
# stack / output is missing or inaccessible.
cfn_output() {
  local stack="$1"
  local key="$2"
  aws cloudformation describe-stacks \
    --stack-name "$stack" \
    --region "$REGION" \
    --query "Stacks[0].Outputs[?OutputKey=='${key}'].OutputValue | [0]" \
    --output text 2>/dev/null || true
}

# emit KEY VALUE -> append "KEY=VALUE" only when VALUE is non-empty and not the
# aws-cli "None" sentinel. Never writes a blank / stale overwrite.
emit() {
  local key="$1"
  local value="$2"
  if [ -n "$value" ] && [ "$value" != "None" ]; then
    printf '%s=%s\n' "$key" "$value" >> "$TMP_FILE"
  fi
}

echo "Generating .env from CloudFormation stacks in $REGION ..."

{
  echo "# Auto-generated by deploy/generate-env.sh — do not edit by hand."
  echo "# Re-run the script to refresh from CloudFormation outputs."
} > "$TMP_FILE"

emit "AWS_REGION" "$REGION"

# --- AgentCore memory ---
emit "SharedMemoryId" "$(cfn_output mladas-agentcore-memory SharedMemoryId)"

# --- AgentCore evaluator ---
emit "ToolSelectionEvaluatorId" "$(cfn_output mladas-agentcore-evaluator ToolSelectionEvaluatorId)"

# --- AgentCore gateway ---
emit "GatewayId" "$(cfn_output mladas-agentcore-gateway GatewayId)"

# --- AgentCore policy engine ---
emit "PolicyEngineId" "$(cfn_output mladas-agentcore-policy PolicyEngineId)"

# --- Bedrock guardrail ---
emit "GuardrailId" "$(cfn_output mladas-agentcore-guardrail GuardrailId)"
emit "GuardrailVersion" "$(cfn_output mladas-agentcore-guardrail GuardrailVersion)"

# --- Module 3 Verified Permissions policy store ---
emit "PolicyStoreId" "$(cfn_output m3-demo-verified-permissions PolicyStoreId)"

# --- Module 3 Cognito (emit both aliases the app accepts) ---
USER_POOL_ID="$(cfn_output m3-demo-cognito UserPoolId)"
emit "UserPoolId" "$USER_POOL_ID"
emit "CognitoUserPoolId" "$USER_POOL_ID"

USER_POOL_CLIENT_ID="$(cfn_output m3-demo-cognito UserPoolClientId)"
emit "UserPoolClientId" "$USER_POOL_CLIENT_ID"
emit "CognitoClientId" "$USER_POOL_CLIENT_ID"

# --- Fixed Module 3 DynamoDB table names (set by cfn-dynamodb.yaml) ---
# These names are fixed by the module 3 template, not resolved resource ids.
printf 'CUSTOMERS_TABLE=m3-demo-customers\n' >> "$TMP_FILE"
printf 'ORDERS_TABLE=m3-demo-orders\n' >> "$TMP_FILE"

mv "$TMP_FILE" "$ENV_FILE"
trap - EXIT

echo "Wrote $ENV_FILE"
